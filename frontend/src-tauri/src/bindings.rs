//! Generates the TypeScript IPC bindings in `frontend/src/lib/ipc/generated/`.
//!
//! The bindings come from a test, so generation is deterministic and needs no
//! running app (anarlog's export-test pattern, MIT):
//!
//! ```sh
//! cargo test -p deino --lib bindings    # then commit frontend/src/lib/ipc/generated/
//! ```
//!
//! Each feature plugin gets `<feature>.ts` with its commands, events and the
//! types they use; `shared.ts` holds the vocabulary every feature shares
//! (`AppError`, `ErrorCode`, `Table`) plus runtime lists of their values. ID
//! types are branded on the way out (`string & { readonly __brand: "MeetingId" }`),
//! so the UI cannot pass one entity's ID where another's is expected. CI
//! regenerates the files and fails when `git diff` shows a change.

use std::collections::BTreeSet;
use std::path::PathBuf;

use deino_db::Table;
use deino_domain::{AppError, ErrorCode};
use specta_typescript::{BigIntExportBehavior, Typescript};

use crate::features::acl::FEATURES;
use crate::features::registry;

/// First lines of every generated file.
const HEADER: &str = "// Generated by `cargo test -p deino --lib bindings` (src-tauri/src/bindings.rs). Do not edit.";

fn output_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/lib/ipc/generated")
}

fn typescript() -> Typescript {
    // IDs and counts fit in a JS number; no field needs BigInt precision.
    Typescript::default()
        .header(HEADER)
        .bigint(BigIntExportBehavior::Number)
}

/// Rewrites `export type FooId = string` as a branded string type.
fn brand_ids(source: &str) -> String {
    source
        .lines()
        .map(|line| {
            let id = line
                .strip_prefix("export type ")
                .and_then(|rest| rest.strip_suffix(" = string"))
                .filter(|name| name.ends_with("Id"));
            match id {
                Some(name) => {
                    format!("export type {name} = string & {{ readonly __brand: \"{name}\" }}\n")
                }
                None => format!("{line}\n"),
            }
        })
        .collect()
}

/// `shared.ts`: the IPC vocabulary and the runtime lists of its values.
fn shared_bindings() -> String {
    let mut types = specta::TypeCollection::default();
    types
        .register::<AppError>()
        .register::<ErrorCode>()
        .register::<Table>();
    let declarations = typescript().export(&types).expect("shared types export");
    let error_codes = serde_json::to_string(&ErrorCode::ALL).expect("codes serialize");
    // A slice: serde implements arrays only up to 32 elements.
    let tables = serde_json::to_string(Table::ALL.as_slice()).expect("tables serialize");
    format!(
        "{declarations}\
         /** Every `ErrorCode`, for validating errors that arrive over IPC. */\n\
         export const ERROR_CODES = {error_codes} as const satisfies readonly ErrorCode[]\n\n\
         /** Every `Table`, for invalidating everything at once. */\n\
         export const TABLES = {tables} as const satisfies readonly Table[]\n"
    )
}

/// Writes `contents` to `<name>.ts`, leaving an unchanged file untouched so
/// the Vite dev server does not reload for nothing.
fn write_binding(name: &str, contents: &str) {
    let path = output_dir().join(format!("{name}.ts"));
    if std::fs::read_to_string(&path).is_ok_and(|current| current == contents) {
        return;
    }
    std::fs::create_dir_all(output_dir()).expect("create the bindings directory");
    std::fs::write(&path, contents).expect("write the bindings file");
}

/// Every registered feature's bindings builder, keyed by the file it is
/// exported to (`<name>.ts`).
fn builders() -> impl Iterator<Item = (&'static str, tauri_specta::Builder<tauri::Wry>)> {
    registry::plugins()
        .into_iter()
        .map(|plugin| (plugin.name, (plugin.specta)()))
}

/// The `plugin:<name>|<command>` strings a generated file invokes.
fn invoked_commands(source: &str) -> BTreeSet<String> {
    source
        .split("TAURI_INVOKE(\"")
        .skip(1)
        .filter_map(|rest| rest.split('"').next())
        .map(str::to_owned)
        .collect()
}

#[test]
fn export_bindings() {
    for (name, builder) in builders() {
        let source = builder
            .export_str(typescript())
            .expect("feature bindings export");
        write_binding(name, &brand_ids(&source));
    }
    write_binding("shared", &brand_ids(&shared_bindings()));
}

/// The generated ACL (`build/features.rs`, from each `collect_commands!`)
/// allows exactly the commands the registered plugins export.
#[test]
fn exported_commands_match_the_acl() {
    let exported: BTreeSet<String> = builders()
        .map(|(_, builder)| {
            builder
                .export_str(typescript())
                .expect("feature bindings export")
        })
        .flat_map(|source| invoked_commands(&source))
        .collect();

    let declared: BTreeSet<String> = FEATURES
        .iter()
        .flat_map(|feature| {
            feature
                .commands
                .iter()
                .map(|cmd| format!("plugin:{}|{cmd}", feature.name))
        })
        .collect();

    assert_eq!(
        exported, declared,
        "the generated ACL and the plugins' commands differ"
    );
}

#[test]
fn id_aliases_are_branded_and_other_types_are_not() {
    let source = "export type MeetingId = string\nexport type Title = string\n";

    assert_eq!(
        brand_ids(source),
        "export type MeetingId = string & { readonly __brand: \"MeetingId\" }\nexport type Title = string\n"
    );
}
