//! Build script: re-exports every ID file, so a new file of IDs in
//! `src/id/` needs only its alphabetical `mod` line in `src/id.rs` (REG-02).
//!
//! `$OUT_DIR/id_exports.rs` (included by `src/id.rs`) is `pub use <module>::*;`
//! for every `src/id/*.rs`; a file without its `mod` line fails the build.
//! See `docs/adr/2026-10-12-settings-self-registration.md`.

use std::path::{Path, PathBuf};

/// One file per area's IDs.
const ID_DIR: &str = "src/id";
/// Where the ID modules are declared.
const ID_MOD: &str = "src/id.rs";

#[allow(clippy::panic, reason = "a build script reports failure by panicking")]
fn main() {
    println!("cargo:rerun-if-changed={ID_DIR}");
    println!("cargo:rerun-if-changed={ID_MOD}");
    if let Err(error) = generate() {
        panic!("generating the ID exports: {error}");
    }
}

fn generate() -> Result<(), String> {
    let declared = std::fs::read_to_string(ID_MOD).map_err(|e| format!("{ID_MOD}: {e}"))?;
    let mut lines =
        vec!["// Generated by deino-domain's build.rs from src/id/. Do not edit.".to_owned()];
    for module in modules(Path::new(ID_DIR))? {
        if !declared
            .lines()
            .any(|line| line == format!("mod {module};"))
        {
            return Err(format!(
                "{ID_DIR}/{module}.rs is not declared: add `mod {module};` to {ID_MOD}"
            ));
        }
        lines.push(format!("pub use {module}::*;"));
    }
    let out_dir = std::env::var("OUT_DIR").map_err(|e| format!("OUT_DIR: {e}"))?;
    let path = Path::new(&out_dir).join("id_exports.rs");
    std::fs::write(&path, lines.join("\n") + "\n").map_err(|e| format!("{}: {e}", path.display()))
}

/// The module names of the `.rs` files directly in `dir`, by name.
fn modules(dir: &Path) -> Result<Vec<String>, String> {
    let entries = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let mut files: Vec<PathBuf> = entries
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "rs"))
        .collect();
    files.sort();
    files
        .iter()
        .map(|file| {
            file.file_stem()
                .and_then(|stem| stem.to_str())
                .map(str::to_owned)
                .ok_or_else(|| format!("{}: not a module name", file.display()))
        })
        .collect()
}
