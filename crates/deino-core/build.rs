//! Build script: generates the settings document from its sections, so a
//! new section is registered by its own file alone (REG-02).
//!
//! - `$OUT_DIR/settings_sections.rs` (included by `settings/sections.rs`):
//!   `pub use <module>::*;` for every file in `src/settings/sections/`.
//! - `$OUT_DIR/settings_model.rs` (included by `settings/model.rs`): one
//!   `settings! { .. }` invocation listing every `register_section!`, sorted
//!   by order then key, and the dialog-only paths the patch refuses to set.
//!
//! See `docs/adr/2026-10-12-settings-self-registration.md`.

#[path = "build/settings.rs"]
mod settings;

use std::path::Path;

use settings::Section;

/// One file per section module.
const SECTIONS: &str = "src/settings/sections";
/// Where the section modules are declared.
const SECTIONS_MOD: &str = "src/settings/sections.rs";

#[allow(clippy::panic, reason = "a build script reports failure by panicking")]
fn main() {
    println!("cargo:rerun-if-changed={SECTIONS}");
    println!("cargo:rerun-if-changed={SECTIONS_MOD}");
    println!("cargo:rerun-if-changed=build");
    if let Err(error) = generate() {
        panic!("generating the settings sections: {error}");
    }
}

fn generate() -> Result<(), String> {
    let (modules, sections) = settings::read(Path::new(SECTIONS))?;
    let declared =
        std::fs::read_to_string(SECTIONS_MOD).map_err(|e| format!("{SECTIONS_MOD}: {e}"))?;
    if let Some(missing) = modules.iter().find(|module| {
        !declared
            .lines()
            .any(|line| line == format!("mod {module};"))
    }) {
        return Err(format!(
            "{SECTIONS}/{missing}.rs is not declared: add `mod {missing};` to {SECTIONS_MOD}"
        ));
    }
    let out_dir = std::env::var("OUT_DIR").map_err(|e| format!("OUT_DIR: {e}"))?;
    write(&out_dir, "settings_sections.rs", &render_exports(&modules))?;
    write(&out_dir, "settings_model.rs", &render_model(&sections))
}

fn write(out_dir: &str, name: &str, contents: &str) -> Result<(), String> {
    let path = Path::new(out_dir).join(name);
    std::fs::write(&path, contents).map_err(|e| format!("{}: {e}", path.display()))
}

/// `pub use <module>::*;` for every section module.
fn render_exports(modules: &[String]) -> String {
    let mut lines = vec![
        "// Generated by deino-core's build.rs from src/settings/sections/. Do not edit."
            .to_owned(),
    ];
    lines.extend(modules.iter().map(|module| format!("pub use {module}::*;")));
    lines.join("\n") + "\n"
}

/// The `settings!` invocation for `sections`.
fn render_model(sections: &[Section]) -> String {
    let mut lines = vec![
        "// Generated by deino-core's build.rs from src/settings/sections/. Do not edit."
            .to_owned(),
        "settings! {".to_owned(),
        "    sections: [".to_owned(),
    ];
    for section in sections {
        lines.extend(section.doc.iter().map(|line| doc_attribute(line)));
        lines.push(format!(
            "        {}: crate::settings::{},",
            section.key, section.ty
        ));
    }
    lines.push("    ]".to_owned());
    lines.push("    dialog_only: [".to_owned());
    for section in sections {
        let json = settings::camel(&section.key);
        for field in &section.dialog_only {
            lines.push(format!(
                "        ({json:?}, {field:?}, \"{json}.{field}\"),"
            ));
        }
    }
    lines.push("    ]".to_owned());
    lines.push("}".to_owned());
    lines.join("\n") + "\n"
}

/// `#[doc = " line"]`, exactly what `/// line` desugars to.
fn doc_attribute(line: &str) -> String {
    let text = if line.is_empty() {
        String::new()
    } else {
        format!(" {line}")
    };
    format!("        #[doc = {text:?}]")
}
