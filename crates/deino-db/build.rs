//! Build script: rebuilds the crate when a migration is added, so
//! `sqlx::migrate!` embeds it, and generates the `Table` list from the
//! migrations, so a new table is registered by its migration alone.
//!
//! `$OUT_DIR/tables.rs` is one `tables! { .. }` invocation (the macro is in
//! `src/table.rs`): every table the migrations leave behind, the frozen
//! tables of `build/legacy_tables.rs` first and in their order, then the rest
//! in the order they first appear.

#[path = "build/legacy_tables.rs"]
mod legacy_tables;
#[path = "build/schema.rs"]
mod schema;

use schema::TableDef;

/// The app database's migrations.
const MIGRATIONS: &str = "migrations";
/// The reference feature's migrations: its table lives in its own in-memory
/// database in debug builds, but the UI tracks it like any other.
const EXAMPLE_MIGRATIONS: &str = "../deino-core/src/_example/migrations";

#[allow(clippy::panic, reason = "a build script reports failure by panicking")]
fn main() {
    println!("cargo:rerun-if-changed={MIGRATIONS}");
    println!("cargo:rerun-if-changed={EXAMPLE_MIGRATIONS}");
    println!("cargo:rerun-if-changed=build");
    if let Err(error) = generate() {
        panic!("generating the Table list: {error}");
    }
}

fn generate() -> Result<(), String> {
    let tables = ordered(schema::tables(&[MIGRATIONS, EXAMPLE_MIGRATIONS])?)?;
    let out_dir = std::env::var("OUT_DIR").map_err(|e| format!("OUT_DIR: {e}"))?;
    let path = std::path::Path::new(&out_dir).join("tables.rs");
    std::fs::write(&path, render(&tables)?).map_err(|e| format!("{}: {e}", path.display()))
}

/// The frozen tables in their order with their docs, then the new ones.
fn ordered(mut found: Vec<TableDef>) -> Result<Vec<TableDef>, String> {
    let mut tables = Vec::with_capacity(found.len());
    for (name, doc) in legacy_tables::DOCUMENTED {
        let Some(index) = found.iter().position(|table| table.name == *name) else {
            return Err(format!(
                "`{name}` is in build/legacy_tables.rs but no migration creates it; remove it there"
            ));
        };
        let mut table = found.remove(index);
        table.doc = doc.iter().map(|line| (*line).to_owned()).collect();
        tables.push(table);
    }
    if let Some(table) = found.iter().find(|table| table.doc.is_empty()) {
        return Err(format!(
            "table `{}` has no doc: write a `--` comment directly above its CREATE TABLE",
            table.name
        ));
    }
    tables.extend(found);
    Ok(tables)
}

/// The `tables!` invocation for `tables`.
fn render(tables: &[TableDef]) -> Result<String, String> {
    let mut lines = vec![
        "// Generated by deino-db's build.rs from the migrations. Do not edit.".to_owned(),
        "tables! {".to_owned(),
        format!("    count: {};", tables.len()),
        "    tables: [".to_owned(),
    ];
    for table in tables {
        lines.extend(table.doc.iter().map(|line| doc_attribute(line)));
        lines.push(format!(
            "        {} = {:?},",
            variant(&table.name)?,
            table.name
        ));
    }
    lines.push("    ]".to_owned());
    lines.push("    by_name: [".to_owned());
    let mut sorted: Vec<&TableDef> = tables.iter().collect();
    sorted.sort_by(|a, b| a.name.cmp(&b.name));
    for table in sorted {
        lines.push(format!(
            "        {:?} => {},",
            table.name,
            variant(&table.name)?
        ));
    }
    lines.push("    ]".to_owned());
    lines.push("}".to_owned());
    Ok(lines.join("\n") + "\n")
}

/// `#[doc = " line"]`, exactly what `/// line` desugars to.
fn doc_attribute(line: &str) -> String {
    let text = if line.is_empty() {
        String::new()
    } else {
        format!(" {line}")
    };
    format!("        #[doc = {text:?}]")
}

/// `meeting_notes` → `MeetingNotes`, checked to serialize back to `name`
/// under `serde(rename_all = "snake_case")`.
fn variant(name: &str) -> Result<String, String> {
    let variant: String = name
        .split('_')
        .map(|word| {
            let mut chars = word.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + chars.as_str()
            })
        })
        .collect();
    let snake: String = variant
        .chars()
        .enumerate()
        .flat_map(|(i, c)| {
            let sep = (i > 0 && c.is_ascii_uppercase()).then_some('_');
            sep.into_iter()
                .chain(std::iter::once(c.to_ascii_lowercase()))
        })
        .collect();
    if snake == name {
        Ok(variant)
    } else {
        Err(format!(
            "table `{name}` has no Rust variant name that serializes back to it"
        ))
    }
}
